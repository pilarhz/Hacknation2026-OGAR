import { spawn } from 'node:child_process';
process.env.DB_PATH = ':memory:'; process.env.SANDBOX_URL = 'http://127.0.0.1:4195'; process.env.CHAIN_LIVE = 'false';
const sb = spawn(process.execPath, ['apps/sandbox/server.ts'], { env: { ...process.env, SANDBOX_PORT: '4195' }, stdio: 'pipe' });
await new Promise<void>((r) => sb.stdout!.on('data', (d) => String(d).includes('Piaskownica') && r()));
const { runInvestigation } = await import('./src/engine/investigate.ts');
const r = (await runInvestigation([{ kind: 'nick', value: 'cryptojanek' }], { sources: ['sandbox', 'web'] })).result;
for (const l of r.requestLog) console.log(l.status, l.cache ? 'CACHE' : '     ', l.url);
console.log('cashout', r.stats.cashOutSignals);
for (const a of r.addresses) console.log(a.score.score, a.address.slice(0, 10), a.score.rules.map((x: any) => x.code + ':' + x.value).join(' '));
for (const c of r.identity) console.log(c.confirmed, c.accounts.map((a: any) => a.site + '/' + a.handle).join(' '), '|', c.reason, '|', c.links.join(' ; '));
for (const c of r.conclusions) console.log('-', c.level, c.text.slice(0, 140));
sb.kill(); process.exit(0);
